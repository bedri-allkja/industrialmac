<h4>2. Cosa sono i cookie?</h4>
<p>I cookie sono piccoli file di dati che vengono memorizzati sul tuo computer o dispositivo mobile quando visiti un sito web. Sono ampiamente utilizzati dai gestori dei siti per far funzionare i siti stessi, migliorarne l’efficienza e fornire informazioni di reportistica.</p>
<p>I cookie impostati dal titolare del sito (in questo caso Industrialmac S.r.l.) sono detti “cookie di prima parte”. I cookie impostati da soggetti diversi dal titolare del sito sono detti “cookie di terze parti”. I cookie di terze parti consentono di fornire funzionalità o servizi aggiuntivi sul sito (ad esempio analytics, contenuti interattivi e pubblicità).</p>

