<h4>5. Gestione e disabilitazione dei cookie</h4>
<p>Hai il diritto di decidere se accettare o rifiutare i cookie. Puoi esercitare le tue preferenze tramite il banner di consenso al primo accesso, oppure in qualsiasi momento tramite le impostazioni di consenso sul sito.</p>
<p><strong>Impostazioni del browser:</strong> puoi anche configurare il browser per accettare o rifiutare i cookie. Se scegli di rifiutarli, potrai comunque utilizzare il sito, ma alcune funzionalità o aree potrebbero risultare limitate.</p>
