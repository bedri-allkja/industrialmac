<p>Non vendiamo, cediamo o affittiamo i vostri dati personali a terzi. Possiamo condividere i dati con fornitori di servizi di fiducia (Responsabili del trattamento) vincolati da contratto, necessari per operare il sito e i servizi, come fornitori di infrastrutture IT, hosting e piattaforme di comunicazione email.</p>
<p>Tutti i fornitori terzi sono legalmente obbligati a mantenere riservatezza e sicurezza dei dati. Se i dati personali vengono trasferiti al di fuori dello Spazio Economico Europeo (SEE), tali trasferimenti avverranno nel rispetto della normativa applicabile, anche mediante clausole contrattuali standard approvate dalla Commissione Europea.</p>

